/**
 * One-time build script (intent doc §6): generate the fixed 4-week matchup
 * tables per team count (12/14/16), used as a static lookup at runtime.
 *
 * Constraints, in priority order:
 *   1. HARD: no team plays the same opponent twice within the cycle.
 *   2. HARD: every team in the same team-generation "time-slot group"
 *      (server/src/teamGeneration/groups.ts) lands in the same draw
 *      (early/late) together, every week — never split. This is what
 *      actually makes "same time-slot group" placement during team
 *      generation (§5 step 2, TimeSlotPair) mean anything: two paired
 *      players placed in the same group are guaranteed to curl at the same
 *      time each week, even though *which* time (early/late) that group
 *      gets can rotate week to week. Confirmed against every week of the
 *      old system's actual matrices (reference/ScheduleGenerator.gs) — it
 *      holds strictly there too, just never stated in the intent doc's
 *      prose. Groups never split across a draw in this generator either.
 *   3. HARD (in practice — see below): every team plays early exactly 2 of
 *      the 4 weeks and late the other 2. A real-world league schedule that
 *      leaves a team almost entirely on one draw time for a whole cycle is
 *      a fairness problem, not a cosmetic one — this was missed in an
 *      earlier version of this script (which flipped early/late with an
 *      independent 50/50 coin toss per week, no memory of prior weeks) and
 *      produced teams stuck at 4 early / 0 late. Confirmed with the user
 *      this ranks above sheet-rotation variety.
 *   4. HARD (in practice — see below): every ghost ("open") game lands on
 *      the same physical sheet, every week, every cycle (GHOST_SHEET,
 *      currently 4) — not just "off the middle sheets" generally, which
 *      let it drift between sheet 1 and sheet 4 week to week (confirmed:
 *      the committed 14-team table had the ghost on sheet 1 some weeks and
 *      sheet 4 others before this). Confirmed with the user: always sheet
 *      4, including both of the 12-team config's two ghosts per week.
 *   5. SOFT / best-effort: each team rotates through as many distinct
 *      sheets as possible across the 4 weeks.
 *
 * Approach:
 *   - The team-pairing + early/late layer is NOT generated by search here
 *     at all. It's lifted verbatim from the old Apps Script system's own
 *     hand-built fixed matrices (reference/ScheduleGenerator.gs,
 *     getFixedSchedule()) — that system evidently *did* account for
 *     early/late balance (its 14-team comment literally annotates each
 *     team's early/late pattern, e.g. "EELL / ELEL / LLEE"), and
 *     verification here confirms every team in all three configs gets a
 *     perfect 2 early / 2 late split. Reusing it outright is far more
 *     reliable than trying to retrofit balance as another scored objective
 *     in a stochastic search — this constraint is just satisfied by
 *     construction instead. Also re-verified here (not just trusted) that
 *     it still satisfies constraints 1 and 2 under this codebase's current
 *     team-generation group definitions (teamGeneration/groups.ts) — it
 *     does, exactly, since those groups are themselves a direct port of
 *     the old system's.
 *   - On top of that fixed pairing, this script still randomly searches
 *     over *sheet-number* assignment only (which of the 4 fixed games in a
 *     draw lands on sheet 1 vs 2 vs 3 vs 4) — shuffling the order weeks/
 *     draws are processed in and keeping whichever ordering scores best —
 *     weighted first to pin any ghost game to GHOST_SHEET (there's always
 *     at most one ghost per draw side in both 12- and 14-team, verified
 *     against FIXED_PAIRINGS, so this is always achievable exactly), then
 *     for the lower-priority sheet-rotation objective. This can't affect
 *     constraints 1, 2, or 3; it only reassigns which sheet a fixed game
 *     is on.
 *
 * Run with: npx tsx scripts/generate-fixed-schedules.ts (from server/)
 */

import { getTimeSlotGroups } from "../src/teamGeneration/groups.js";

type TeamCount = 12 | 14 | 16;
type Game = [number, number];
type Draw = { early: Game[]; late: Game[] };

function shuffle<T>(items: T[]): T[] {
  const arr = items.slice();
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

function permutations<T>(items: T[]): T[][] {
  if (items.length <= 1) return [items];
  const result: T[][] = [];
  for (let i = 0; i < items.length; i++) {
    const rest = [...items.slice(0, i), ...items.slice(i + 1)];
    for (const perm of permutations(rest)) result.push([items[i], ...perm]);
  }
  return result;
}

// --- Fixed team-pairing + early/late layer, verbatim from the old system
// (reference/ScheduleGenerator.gs, getFixedSchedule()) — see the file
// header for why this is lifted rather than re-derived by search. Ghost
// "team" numbers here are whatever the old system happened to use (not
// necessarily teamCount+1/+2); that's fine, generateMatches.ts only checks
// `> teamCount` to decide isGhost, it never looks the ghost numbers up.
const FIXED_PAIRINGS: Record<TeamCount, Draw[]> = {
  16: [
    { early: [[1, 2], [3, 4], [5, 6], [7, 8]], late: [[9, 10], [11, 12], [13, 14], [15, 16]] },
    { early: [[14, 16], [13, 15], [9, 11], [10, 12]], late: [[6, 8], [5, 7], [1, 3], [2, 4]] },
    { early: [[1, 12], [5, 16], [7, 10], [3, 14]], late: [[2, 11], [8, 9], [4, 13], [6, 15]] },
    { early: [[4, 15], [2, 13], [6, 9], [8, 11]], late: [[5, 14], [1, 10], [3, 12], [7, 16]] },
  ],
  14: [
    { early: [[1, 2], [3, 4], [5, 6], [7, 8]], late: [[9, 10], [11, 12], [13, 14], [15, 16]] },
    { early: [[1, 9], [3, 11], [5, 13], [15, 16]], late: [[2, 10], [4, 12], [6, 8], [7, 14]] },
    { early: [[2, 12], [4, 10], [6, 14], [7, 9]], late: [[1, 11], [3, 13], [5, 8], [15, 16]] },
    { early: [[8, 12], [10, 14], [11, 13], [15, 16]], late: [[1, 3], [2, 9], [4, 5], [6, 7]] },
  ],
  12: [
    { early: [[1, 7], [3, 9], [5, 11], [13, 14]], late: [[2, 8], [4, 10], [6, 12], [15, 16]] },
    { early: [[1, 10], [3, 12], [5, 8], [13, 15]], late: [[2, 9], [4, 11], [6, 7], [14, 16]] },
    { early: [[2, 10], [4, 12], [6, 8], [13, 16]], late: [[1, 9], [3, 11], [5, 7], [14, 15]] },
    { early: [[2, 11], [4, 7], [6, 9], [13, 14]], late: [[1, 12], [3, 8], [5, 10], [15, 16]] },
  ],
};

// The open sheet should always be the SAME physical sheet, every week,
// every cycle — not just "off the middle sheets" (which let it drift
// between sheet 1 and sheet 4 week to week, confirmed against the
// committed data before this fix: the 14-team ghost landed on sheet 1 in
// some weeks and sheet 4 in others). Confirmed with the user: sheet 4,
// for both the 12-team config's two ghosts-per-week and the 14-team
// config's one. There's always at most one ghost game per draw side in
// both configs (verified against FIXED_PAIRINGS), so "pin the one ghost
// in a draw to sheet 4" is unambiguous.
const GHOST_SHEET = 4;

function orderForSheetVariety(games: Game[], teamCount: TeamCount, sheetsUsed: Map<number, Set<number>>): Game[] {
  let best = games;
  let bestScore = Infinity;
  for (const perm of permutations(games)) {
    let repeatScore = 0;
    let ghostSheetPenalty = 0;
    perm.forEach((game, idx) => {
      const sheet = idx + 1;
      const isGhostGame = game[0] > teamCount;
      if (isGhostGame) {
        if (sheet !== GHOST_SHEET) ghostSheetPenalty++;
        return;
      }
      for (const team of game) {
        if (sheetsUsed.get(team)?.has(sheet)) repeatScore++;
      }
    });
    const score = ghostSheetPenalty * 100 + repeatScore;
    if (score < bestScore) {
      bestScore = score;
      best = perm;
    }
  }
  best.forEach((game, idx) => {
    const sheet = idx + 1;
    for (const team of game) {
      if (team > teamCount) continue;
      if (!sheetsUsed.has(team)) sheetsUsed.set(team, new Set());
      sheetsUsed.get(team)!.add(sheet);
    }
  });
  return best;
}

// Processes weeks/draws in a shuffled order each call so repeated trials
// explore different greedy paths through the shared `sheetsUsed` state —
// the team-pairing/early-late layer is fixed (FIXED_PAIRINGS above), only
// this sheet-number assignment is still searched.
function applySheetVarietyRandomOrder(schedule: Draw[], teamCount: TeamCount): Draw[] {
  const sheetsUsed = new Map<number, Set<number>>();
  const result: Draw[] = schedule.map((w) => ({ early: w.early, late: w.late }));
  const slots = shuffle(
    schedule.flatMap((_, weekIdx) => [
      { weekIdx, side: "early" as const },
      { weekIdx, side: "late" as const },
    ]),
  );
  for (const { weekIdx, side } of slots) {
    result[weekIdx][side] = orderForSheetVariety(schedule[weekIdx][side], teamCount, sheetsUsed);
  }
  return result;
}

// Two-tier weighting, highest priority first:
//   1. No team ever plays the same sheet 3+ times (worst case must stay at
//      2x — confirmed acceptable, explicitly called the ideal outcome).
//   2. Keep the (single, per draw) ghost game pinned to GHOST_SHEET.
//   3. Real-team sheet-rotation variety — only a tiebreak once 1 and 2 are
//      otherwise equal (or moot — no ghosts at all for 16-team).
function scheduleScore(schedule: Draw[], teamCount: TeamCount): number {
  const sheetsUsed = new Map<number, number[]>();
  let ghostMisplacedCount = 0;
  for (const week of schedule) {
    for (const draw of [week.early, week.late]) {
      draw.forEach(([a, b], idx) => {
        const sheet = idx + 1;
        if (a > teamCount) {
          if (sheet !== GHOST_SHEET) ghostMisplacedCount++;
          return;
        }
        for (const team of [a, b]) {
          if (!sheetsUsed.has(team)) sheetsUsed.set(team, []);
          sheetsUsed.get(team)!.push(sheet);
        }
      });
    }
  }
  let repeats = 0;
  let worstRepeatViolations = 0;
  for (const sheets of sheetsUsed.values()) {
    repeats += sheets.length - new Set(sheets).size;
    const counts = new Map<number, number>();
    for (const s of sheets) counts.set(s, (counts.get(s) ?? 0) + 1);
    const worst = Math.max(...counts.values());
    if (worst > 2) worstRepeatViolations += worst - 2;
  }
  return worstRepeatViolations * 10000 + ghostMisplacedCount * 100 + repeats;
}

const TRIALS = 20000;

function generateSchedule(teamCount: TeamCount): Draw[] {
  const basePairing = FIXED_PAIRINGS[teamCount];
  let best: Draw[] | null = null;
  let bestScore = Infinity;

  for (let i = 0; i < TRIALS && bestScore > 0; i++) {
    const withSheets = applySheetVarietyRandomOrder(basePairing, teamCount);
    const score = scheduleScore(withSheets, teamCount);
    if (score < bestScore) {
      bestScore = score;
      best = withSheets;
    }
  }

  if (!best) throw new Error(`Could not construct a valid ${teamCount}-team schedule at all — this shouldn't happen.`);
  return best;
}

// --- Verification -----------------------------------------------------

function verify(schedule: Draw[], teamCount: TeamCount) {
  const opponentsSeen = new Map<number, Set<number>>();
  const sheetsUsed = new Map<number, number[]>();
  const drawTimeCounts = new Map<number, { early: number; late: number }>();
  const groups = getTimeSlotGroups(teamCount);
  let hardViolations = 0;
  let groupSplitViolations = 0;
  let ghostGameCount = 0;
  let ghostMisplacedCount = 0;

  for (const week of schedule) {
    for (const [drawName, draw] of [["early", week.early], ["late", week.late]] as const) {
      draw.forEach((game, idx) => {
        const sheet = idx + 1;
        const [a, b] = game;
        const isGhostGame = a > teamCount || b > teamCount;
        if (isGhostGame) {
          ghostGameCount++;
          if (sheet !== GHOST_SHEET) ghostMisplacedCount++;
        } else {
          if (!opponentsSeen.has(a)) opponentsSeen.set(a, new Set());
          if (!opponentsSeen.has(b)) opponentsSeen.set(b, new Set());
          if (opponentsSeen.get(a)!.has(b)) hardViolations++;
          opponentsSeen.get(a)!.add(b);
          opponentsSeen.get(b)!.add(a);
          for (const team of [a, b]) {
            if (!sheetsUsed.has(team)) sheetsUsed.set(team, []);
            sheetsUsed.get(team)!.push(sheet);
            if (!drawTimeCounts.has(team)) drawTimeCounts.set(team, { early: 0, late: 0 });
            drawTimeCounts.get(team)![drawName]++;
          }
        }
      });
    }

    // Group-atomicity check: every group's real teams must be entirely
    // within one draw this week.
    for (const group of groups) {
      const realTeams = group.filter((t) => t <= teamCount);
      if (realTeams.length === 0) continue;
      const inEarly = realTeams.filter((t) => week.early.some((g) => g.includes(t))).length;
      const inLate = realTeams.filter((t) => week.late.some((g) => g.includes(t))).length;
      if (inEarly > 0 && inLate > 0) groupSplitViolations++;
    }
  }

  let perfectVariety = 0;
  let totalDistinct = 0;
  let worstSingleSheetRepeat = 0;
  for (let team = 1; team <= teamCount; team++) {
    const sheets = sheetsUsed.get(team) ?? [];
    const distinct = new Set(sheets).size;
    totalDistinct += distinct;
    if (distinct === sheets.length) perfectVariety++;
    const counts = new Map<number, number>();
    for (const s of sheets) counts.set(s, (counts.get(s) ?? 0) + 1);
    worstSingleSheetRepeat = Math.max(worstSingleSheetRepeat, ...counts.values());
  }

  let drawTimeImbalances = 0;
  for (let team = 1; team <= teamCount; team++) {
    const c = drawTimeCounts.get(team) ?? { early: 0, late: 0 };
    if (c.early !== 2 || c.late !== 2) drawTimeImbalances++;
  }

  console.log(`\n--- ${teamCount}-team verification ---`);
  console.log(`Hard violations — repeat opponents: ${hardViolations}`);
  console.log(`Hard violations — a time-slot group split across draws in a week: ${groupSplitViolations}`);
  console.log(`Teams NOT exactly 2 early / 2 late across the cycle: ${drawTimeImbalances}/${teamCount}`);
  console.log(`Teams with all-distinct sheets across their games: ${perfectVariety}/${teamCount}`);
  console.log(`Average distinct sheets per team: ${(totalDistinct / teamCount).toFixed(2)} (max possible 4)`);
  // The metric that actually matters more than the average: does any team
  // get stuck on the same sheet repeatedly? 2x (one repeat, otherwise
  // varied) is fine; 3x or 4x would mean a team is effectively parked on
  // one sheet all cycle.
  console.log(`Worst case — most times any one team played the same sheet: ${worstSingleSheetRepeat}x`);
  console.log(`Ghost games NOT on sheet ${GHOST_SHEET}: ${ghostMisplacedCount}/${ghostGameCount} (should be 0)`);

  return {
    hardViolations,
    groupSplitViolations,
    drawTimeImbalances,
    ghostMisplacedCount,
    perfectVariety,
    avgDistinct: totalDistinct / teamCount,
    worstSingleSheetRepeat,
    ghostGameCount,
  };
}

function formatSchedule(schedule: Draw[]): string {
  const lines: string[] = ["["];
  schedule.forEach((week) => {
    lines.push("    {");
    lines.push(`      early: ${JSON.stringify(week.early)},`);
    lines.push(`      late: ${JSON.stringify(week.late)},`);
    lines.push("    },");
  });
  lines.push("  ]");
  return lines.join("\n");
}

async function main() {
  console.log(`\n=== Generating tables (up to ${TRIALS} sheet-ordering trials each) ===`);
  const results: Record<TeamCount, Draw[]> = { 12: [], 14: [], 16: [] };
  const summaries: string[] = [];

  for (const teamCount of [12, 14, 16] as const) {
    const schedule = generateSchedule(teamCount);
    const stats = verify(schedule, teamCount);
    if (
      stats.hardViolations > 0 ||
      stats.groupSplitViolations > 0 ||
      stats.drawTimeImbalances > 0 ||
      stats.ghostMisplacedCount > 0
    ) {
      throw new Error(
        `${teamCount}-team schedule has ${stats.hardViolations} repeat-opponent violation(s), ${stats.groupSplitViolations} group-split violation(s), ${stats.drawTimeImbalances} team(s) not evenly split early/late, and ${stats.ghostMisplacedCount} ghost game(s) not on sheet ${GHOST_SHEET} — refusing to write output.`,
      );
    }
    results[teamCount] = schedule;
    const ghostNote = stats.ghostGameCount > 0 ? `, ${stats.ghostGameCount} ghost game(s) always on sheet ${GHOST_SHEET}` : "";
    summaries.push(
      `// ${teamCount} teams: every team exactly 2 early / 2 late, ${stats.perfectVariety}/${teamCount} teams get all-distinct sheets, avg ${stats.avgDistinct.toFixed(2)}/4${ghostNote}`,
    );
  }

  const fs = await import("node:fs");
  const path = await import("node:path");
  const outDir = path.join(import.meta.dirname, "..", "src", "scheduleGeneration");
  fs.mkdirSync(outDir, { recursive: true });

  const header = `// GENERATED by scripts/generate-fixed-schedules.ts — do not hand-edit.
// Re-run the script and replace this file if the generation approach changes.
//
// Fixed 4-week matchup tables per team count (intent doc §6). Hard by
// construction: no repeat opponents within a cycle, every team-generation
// time-slot group (teamGeneration/groups.ts) stays entirely within one
// draw each week (never split — what makes a TimeSlotPair's "same
// time-slot group" placement actually mean "always plays at the same
// time"), every team plays exactly 2 early / 2 late across the cycle (the
// team-pairing + early/late layer is lifted verbatim from the old Apps
// Script system's own hand-tuned matrices, not generated by search — see
// the generator script's header for why), and every ghost ("open") game
// is always on sheet ${GHOST_SHEET} — the same physical sheet is open every
// week, every cycle, rather than drifting between sheets that happen to
// be off the middle. On top of that, best-effort via randomized search:
// real-team sheet-rotation variety across the cycle.
${summaries.join("\n")}
//
// Game = [teamNumberA, teamNumberB]. Team numbers beyond a config's real
// team count are ghosts (render as "open" — see intent doc §2) and only
// ever face other ghosts. Array index within early/late = sheet number - 1.

export type TeamCount = 12 | 14 | 16;
export type Game = [number, number];
export type WeekSchedule = { early: Game[]; late: Game[] };

export const FIXED_SCHEDULES: Record<TeamCount, WeekSchedule[]> = {
  12: ${formatSchedule(results[12])},
  14: ${formatSchedule(results[14])},
  16: ${formatSchedule(results[16])},
};
`;

  const outFile = path.join(outDir, "fixedSchedules.ts");
  fs.writeFileSync(outFile, header, "utf8");
  console.log(`\nWrote ${outFile}`);
}

main();
